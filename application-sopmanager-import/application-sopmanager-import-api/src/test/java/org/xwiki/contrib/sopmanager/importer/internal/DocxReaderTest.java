    @Test
    void readInvalidFiles() throws Exception
    {
        DocumentReadException damaged = assertThrows(DocumentReadException.class,
            () -> read("ANA_AA_9.104_Dummy-beschaedigt.docx"));
        assertTrue(damaged.getMessage().startsWith("Not a Word document"), damaged.getMessage());
        assertThrows(DocumentReadException.class, () -> read("~$A_AA_9.101_Dummy-Haendedesinfektion.docx"));

        Path noDocument = this.folder.resolve("noDocument.docx");
        write(noDocument, Map.of("word/styles.xml", "<w:styles " + W + "/>"));
        assertEquals("Not a Word document: no main part.",
            assertThrows(DocumentReadException.class, () -> new DocxPackage(noDocument)).getMessage());

        Path noBody = this.folder.resolve("noBody.docx");
        write(noBody, Map.of("word/document.xml", "<w:document " + W + "/>"));
        assertEquals("Not a Word document: no body.",
            assertThrows(DocumentReadException.class, () -> new DocxReader(new DocxPackage(noBody)).read()).getMessage());

        Path notXML = this.folder.resolve("notXML.docx");
        write(notXML, Map.of("word/document.xml", "<w:document"));
        assertTrue(assertThrows(DocumentReadException.class, () -> new DocxReader(new DocxPackage(notXML)).read())
            .getMessage().startsWith("The part [word/document.xml] is not valid"));

        // No DTD, so no external entity.
        Path entity = this.folder.resolve("entity.docx");
        write(entity, Map.of("word/document.xml", "<!DOCTYPE d [<!ENTITY e SYSTEM \"file:///etc/passwd\">]>"
            + "<w:document " + W + "><w:body><w:p><w:r><w:t>&e;</w:t></w:r></w:p></w:body></w:document>"));
        assertThrows(DocumentReadException.class, () -> new DocxReader(new DocxPackage(entity)).read());
    }

    @Test
    void readDocumentWithOtherStructures() throws Exception
    {
        String body = paragraph("<w:r><mc:AlternateContent><mc:Choice Requires=\"wps\"><w:drawing><wp:anchor "
            + "behindDoc=\"0\"><wps:txbx><w:txbxContent>" + text("ANA") + text("_") + text("AA") + text("_")
            + text("7.300") + text(" ") + text("Titel im Textfeld") + "</w:txbxContent></wps:txbx></wp:anchor>"
            + "</w:drawing></mc:Choice><mc:Fallback><w:pict><v:shape><v:textbox><w:txbxContent>"
            + text("ANA_AA_7.300 Titel im Textfeld") + "</w:txbxContent></v:textbox></v:shape></w:pict>"
            + "</mc:Fallback></mc:AlternateContent></w:r>")
            // A hyperlink, a field showing its result, struck out and underlined text, a line break.
            + paragraph("<w:hyperlink r:id=\"rIdLink\"><w:r><w:t>XWiki</w:t></w:r></w:hyperlink>"
                + "<w:r><w:t xml:space=\"preserve\"> Seite </w:t></w:r>"
                + "<w:r><w:fldChar w:fldCharType=\"begin\"/></w:r><w:r><w:instrText>PAGE</w:instrText></w:r>"
                + "<w:r><w:fldChar w:fldCharType=\"separate\"/></w:r><w:r><w:t>3</w:t></w:r>"
                + "<w:r><w:fldChar w:fldCharType=\"end\"/></w:r>"
                + "<w:r><w:rPr><w:strike/></w:rPr><w:t xml:space=\"preserve\"> alt </w:t></w:r>"
                + "<w:r><w:rPr><w:b w:val=\"0\"/><w:u w:val=\"single\"/></w:rPr><w:t>neu</w:t></w:r>"
                + "<w:r><w:br/><w:t>{{velocity}}</w:t><w:tab/><w:noBreakHyphen/></w:r>"
                + "<w:del><w:r><w:delText>gelöscht</w:delText></w:r></w:del>"
                + "<w:ins><w:r><w:t>eingefügt</w:t></w:r></w:ins>")
            // Nested lists, a bulleted list after a numbered item, closed by a paragraph.
            + listItem("Eins", 0) + listItem("Unterpunkt", 1) + listItem("Zwei", 0)
            + listItem("Punkt", 0).replace("w:numId w:val=\"1\"", "w:numId w:val=\"2\"") + paragraph(text("Ende"))
            // Merged cells, the cells of the header row and the shaded cells being header cells.
            + "<w:tbl><w:tr><w:trPr><w:tblHeader/></w:trPr>" + cell("A", "<w:gridSpan w:val=\"2\"/>")
            + cell("B", "<w:vMerge w:val=\"restart\"/>") + "</w:tr><w:tr>" + cell("C", shading("E6E6E6"))
            + cell("D", shading("auto")) + cell("", "<w:vMerge/>") + "</w:tr><w:tr>" + cell("E", shading("FFFFFF"))
            + cell("F", "") + cell("", "<w:vMerge/>")
            + "</w:tr></w:tbl>"
            // A cell with a list: the numbering of the document continues.
            + "<w:tbl><w:tr><w:tc>" + listItem("In der Zelle", 0) + "</w:tc></w:tr></w:tbl>"
            // A structured document tag, and an image behind the text drawn with VML.
            + "<w:sdt><w:sdtContent>" + paragraph(text("Im Inhaltssteuerelement")) + "</w:sdtContent></w:sdt>"
            + paragraph("<w:r><w:pict><v:shape style=\"position:absolute;z-index:-3\"><v:imagedata r:id=\"rIdImage\"/>"
                + "</v:shape></w:pict></w:r>")
            // The release details on one line, and the name of the original document.
            + paragraph(text("Freigabe am/durch: 19.07.2022, Dr. S. Muster Erstellung/Prüfung: QM Revision am: 07/2025"))
            + paragraph(text("ANA_AA_7.300_Titel im Textfeld"))
            + "<w:sectPr><w:pgSz w:w=\"16838\" w:h=\"11906\"/></w:sectPr>";
        Path file = this.folder.resolve("other.docx");
        write(file, Map.of("word/document.xml", "<w:document " + W + "><w:body>" + body + "</w:body></w:document>",
            "word/_rels/document.xml.rels", String.format(RELATIONSHIPS,
                "<Relationship Id=\"rIdLink\" Type=\"" + REL + "hyperlink\" Target=\"https://xwiki.org\" "
                    + "TargetMode=\"External\"/><Relationship Id=\"rIdImage\" Type=\"" + REL + "image\" "
                    + "Target=\"media/../media/image1.png\"/><Relationship Id=\"rIdNumbering\" Type=\"" + REL
                    + "numbering\" Target=\"/word/numbering.xml\"/>"),
            "word/media/image1.png", "png",
            "word/numbering.xml", "<w:numbering " + W + "><w:abstractNum w:abstractNumId=\"0\"><w:lvl w:ilvl=\"1\">"
                + "<w:numFmt w:val=\"bullet\"/></w:lvl></w:abstractNum><w:abstractNum w:abstractNumId=\"1\">"
                + "<w:lvl w:ilvl=\"0\"><w:numFmt w:val=\"bullet\"/></w:lvl></w:abstractNum><w:num w:numId=\"1\">"
                + "<w:abstractNumId w:val=\"0\"/></w:num><w:num w:numId=\"2\"><w:abstractNumId w:val=\"1\"/>"
                + "</w:num></w:numbering>"));

        ImportedDocument docx = new DocxReader(new DocxPackage(file)).read();

        assertEquals(Compatibility.HEADER_FOOTER_IN_CONTENT, docx.compatibility());
        assertTrue(docx.landscape());
        SOPDocumentDetails details = docx.details();
        assertEquals("ANA_AA_7.300", details.getRevisionId());
        assertEquals("Titel im Textfeld", details.getTitle());
        assertEquals(LocalDate.of(2022, 7, 19), details.getReleaseDate());
        assertEquals("Dr. S. Muster", details.getApprovedBy());
        assertEquals("QM", details.getRevisedBy());
        assertEquals(LocalDate.of(2025, 7, 1), details.getRevisionPlannedDate());
        assertEquals(List.of(new ImportWarning("sopManager.import.warning.backgroundImages", 1)), docx.warnings());
        assertEquals("[[XWiki>>url:https://xwiki.org]] Seite 3 --alt-- __neu__\n"
            + "~{~{velocity}} -eingefügt\n\n"
            + "(% class=\"sop-list\" %)\n"
            + "1. Eins\n"
            + "1*. Unterpunkt\n"
            + "1. Zwei\n\n"
            + "* Punkt\n\n"
            + "Ende\n\n"
            + "|=(% colspan=\"2\" %)A|=(% rowspan=\"3\" %)B\n"
            + "|=C|D\n"
            + "|E|F\n\n"
            + "|(((\n(% start=\"3\" class=\"sop-list\" %)\n1. In der Zelle\n)))\n\n"
            + "Im Inhaltssteuerelement", render(docx.content()));
    }

    private static String text(String text)
    {
        return paragraph("<w:r><w:t xml:space=\"preserve\">" + text + "</w:t></w:r>");
    }

    private static String paragraph(String content)
    {
        return content.startsWith("<w:p>") ? content : "<w:p>" + content + "</w:p>";
    }

    private static String listItem(String text, int level)
    {
        return "<w:p><w:pPr><w:numPr><w:ilvl w:val=\"" + level + "\"/><w:numId w:val=\"1\"/></w:numPr></w:pPr>"
            + "<w:r><w:t>" + text + "</w:t></w:r></w:p>";
    }

    private static String cell(String text, String properties)
    {
        return "<w:tc><w:tcPr>" + properties + "</w:tcPr>" + paragraph("<w:r><w:t>" + text + "</w:t></w:r>")
            + "</w:tc>";
    }

    private static String shading(String fill)
    {
        return "<w:shd w:val=\"clear\" w:color=\"auto\" w:fill=\"" + fill + "\"/>";
    }

    private static void write(Path file, Map<String, String> parts) throws IOException
    {
        try (OutputStream output = Files.newOutputStream(file); ZipOutputStream zip = new ZipOutputStream(output)) {
            for (Map.Entry<String, String> part : parts.entrySet()) {
                zip.putNextEntry(new ZipEntry(part.getKey()));
                zip.write(part.getValue().getBytes(StandardCharsets.UTF_8));
                zip.closeEntry();
            }
        }
    }
