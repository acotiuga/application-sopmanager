package org.xwiki.contrib.sopmanager.importer.internal;

import java.net.URISyntaxException;
import java.net.URL;
import java.nio.file.Path;
import java.nio.file.Paths;

import static org.junit.jupiter.api.Assumptions.assumeTrue;

/**
 * The documents read by the tests, generated by {@code src/test/documents/generate.py} in
 * {@code src/test/resources/documents}. They are not part of the sources: the tests reading them are skipped when they
 * are missing.
 *
 * @version $Id$
 */
public final class TestDocuments
{
    private static final String FOLDER = "/documents";

    private TestDocuments()
    {
    }

    /**
     * @param name the name of a document
     * @return the document, the test being skipped if it's missing
     * @throws URISyntaxException if the path of the document is invalid
     */
    public static Path get(String name) throws URISyntaxException
    {
        return get(FOLDER + '/' + name, name);
    }

    /**
     * @return the folder of the documents, the test being skipped if it's missing
     * @throws URISyntaxException if the path of the folder is invalid
     */
    public static Path getFolder() throws URISyntaxException
    {
        return get(FOLDER, FOLDER);
    }

    private static Path get(String resource, String name) throws URISyntaxException
    {
        URL url = TestDocuments.class.getResource(resource);
        assumeTrue(url != null, () -> "Missing test document [" + name + "]: generate it with generate.py.");
        return Paths.get(url.toURI());
    }
}
