/**
 * Unit tests for {@link PdfReader}, on the PDF documents exported by LibreOffice from the documents generated by
 * {@code src/test/documents/generate.py}, and on tagged PDF documents written by the tests as Word writes them.
 *
 * @version $Id$
 */
class PdfReaderTest
{
    private static BlockRenderer renderer;

    @TempDir
    private Path folder;

    @BeforeAll
    static void beforeAll() throws Exception
    {
        EmbeddableComponentManager componentManager = new EmbeddableComponentManager();
        componentManager.initialize(PdfReaderTest.class.getClassLoader());
        renderer = componentManager.getInstance(BlockRenderer.class, "xwiki/2.1");
    }

    private static ImportedDocument read(String name) throws Exception
    {
        return new PdfReader(Paths.get(PdfReaderTest.class.getResource("/documents/" + name).toURI())).read();
    }

    private static String render(XDOM content)
    {
        DefaultWikiPrinter printer = new DefaultWikiPrinter();
        renderer.render(content, printer);
        return printer.toString();
    }

    @Test
    void readPdfExportedFromWordDocument() throws Exception
    {
        ImportedDocument pdf = read("ANA_AA_9.101_Dummy-Haendedesinfektion.pdf");

        assertEquals(Compatibility.TAGGED_PDF, pdf.compatibility());
        assertFalse(pdf.landscape());
        assertEquals(List.of("figure-1.png"), List.copyOf(pdf.images().keySet()));
        SOPDocumentDetails details = pdf.details();
        assertEquals("ANA_AA_9.101", details.getRevisionId());
        assertEquals("Dummy Händedesinfektion", details.getTitle());
        assertEquals(LocalDate.of(2025, 11, 5), details.getReleaseDate());
        assertEquals(LocalDate.of(2028, 11, 4), details.getRevisionPlannedDate());
        assertEquals(5, details.getRevisionNumber());
        assertEquals("Dr. M. Muster", details.getApprovedBy());
        assertEquals("K. Beispiel", details.getRevisedBy());
        assertEquals(List.of(), pdf.warnings());
        assertEquals("Writer", pdf.source().application());
        assertEquals("Dummy", pdf.source().author());
        assertEquals("|Geltungsbereich|Alle Stationen\n"
            + "|Berufsgruppe|Pflegerische und ärztliche Mitarbeiter\n"
            + "|Ziel|Vermeidung von Infektionen\n\n"
            + "**Vorgehen**\n\n"
            + "(% style=\"list-style-type: gkh-decimal-parenthesis\" class=\"sop-list\" %)\n"
            + "1. Die Hände werden vor und nach jedem Patientenkontakt desinfiziert.\n"
            + "1. Das Desinfektionsmittel wird 30 Sekunden **vollständig** eingerieben.\n"
            + "(% style=\"list-style-type: gkh-lower-alpha-parenthesis\" class=\"sop-list\" %)\n"
            + "11. Die Fingerkuppen und Daumen werden //besonders// beachtet.\n"
            + "1. Schmuck und Uhren werden vor Dienstbeginn abgelegt.\n\n"
            + "(% style=\"margin-left: 1.25cm\" %)\n"
            + "Die Hände trocknen an der Luft.\n\n"
            + "**Material**\n\n"
            + "* Händedesinfektionsmittel\n"
            + "* Hautpflegemittel\n\n"
            + "**Dosierung**\n\n"
            + "|**Situation**|**Menge**\n"
            + "|Hygienische Händedesinfektion|3 ml\n"
            + "|Chirurgische Händedesinfektion|2 x 5 ml\n\n"
            + "[[image:figure-1.png||width=\"168\"]]\n\n"
            + "Weitere Hinweise im Hygieneplan.", render(pdf.content()));
    }

    @Test
    void readOriginalPdfOfConvertedDocument() throws Exception
    {
        ImportedDocument pdf = read("ANA_AA_9.102_Dummy-Bestueckung-Notfallwagen.pdf");

        assertTrue(pdf.landscape());
        assertEquals("Dummy Bestückung Notfallwagen", pdf.details().getTitle());
        assertEquals(LocalDate.of(2024, 1, 23), pdf.details().getReleaseDate());
        assertEquals(2, pdf.details().getRevisionNumber());
        assertEquals("W:\\Gemeinsam\\QM\\Dokumentenlenkung\\Dokumente\\ANA_AA_9.102_Dummy-Bestueckung-Notfallwagen.doc",
            pdf.source().originalDocument());
        assertEquals("|Geltungsbereich|Anästhesie\n"
            + "|Berufsgruppe|Pflegedienst\n"
            + "|Ziel|Vollständige Bestückung der Notfallwagen\n\n"
            + "|(% colspan=\"3\" %)**Schublade 1**\n"
            + "|2 Amp. Adrenalin|2 Amp. Atropin|5 x Kanülen 20G\n\n"
            + "|(% colspan=\"2\" %)**Schublade 2**\n"
            + "|10 x Spritzen 10 ml|5 x Spritzen 5 ml\n"
            + "||5 x Spritzen 2 ml", render(pdf.content()));
    }

    @Test
    void readPdfWithoutStructure()
    {
        UnsupportedDocumentException exception =
            assertThrows(UnsupportedDocumentException.class, () -> read("ANA_AA_9.106_Dummy-Scan.pdf"));

        assertEquals(new ImportWarning("sopManager.import.message.untaggedPdf"), exception.getReason());
    }

    @Test
    void readInvalidPdf() throws Exception
    {
        Path file = Files.writeString(this.folder.resolve("invalid.pdf"), "Not a PDF", StandardCharsets.UTF_8);

        DocumentReadException exception =
            assertThrows(DocumentReadException.class, () -> new PdfReader(file).read());

        assertTrue(exception.getMessage().startsWith("Not a valid PDF: "), exception.getMessage());
        assertThrows(DocumentReadException.class, () -> new PdfReader(this.folder.resolve("missing.pdf")).read());
    }

    @Test
    void readPdfWrittenByWord() throws Exception
    {
        Path file;
        try (TaggedPdf pdf = new TaggedPdf()) {
            writeHeaderFooter(pdf);
            PDStructureElement document = pdf.getRoot();
            pdf.line(pdf.element("H1", document), 72, 740, new TaggedPdf.Run("Einleitung", BOLD));
            // A paragraph type of Word, mapped to a standard type.
            PDStructureElement paragraph = pdf.element("Textkörper", document);
            float italicStart = 72 + REGULAR.getStringWidth("Ein Absatz mit ") / 100;
            pdf.line(paragraph, 72, 720, new TaggedPdf.Run("Ein Absatz mit ", REGULAR));
            pdf.line(paragraph, italicStart, 720, new TaggedPdf.Run("kursivem", ITALIC),
                new TaggedPdf.Run(" Text.", REGULAR));
            // A word hyphenated at the end of a line, and a hyphen between two words.
            PDStructureElement hyphenated = pdf.element("P", document);
            pdf.line(hyphenated, 72, 700, "Die Hände werden geschaf-");
            pdf.line(hyphenated, 72, 688, "fen, bei OP-");
            pdf.line(hyphenated, 72, 676, "Beginn.");
            pdf.element("P", document);
            writeLists(pdf, document);
            writeTable(pdf, document);
            pdf.figure(document, 72, 300, true);
            pdf.figure(document, 140, 300, false);
            PDStructureElement container = pdf.element("Div", document);
            pdf.line(container, 72, 280, "Hinweis");
            pdf.line(pdf.element("P", container), 72, 268, "Im Container.");
            file = pdf.save(this.folder.resolve("word.pdf"));
        }

        ImportedDocument pdf = new PdfReader(file).read();

        SOPDocumentDetails details = pdf.details();
        assertEquals("ANA_AA_9.201", details.getRevisionId());
        assertEquals("Synthetische Anweisung", details.getTitle());
        assertEquals(LocalDate.of(2026, 2, 1), details.getReleaseDate());
        assertEquals("Dr. Test", details.getApprovedBy());
        assertEquals(3, details.getRevisionNumber());
        assertEquals(LocalDate.of(2029, 2, 1), details.getRevisionPlannedDate());
        assertEquals("W:\\QM\\ANA_AA_9.201_Synthetisch.doc", pdf.source().originalDocument());
        assertNull(pdf.source().application());
        assertEquals(List.of("figure-1.png"), List.copyOf(pdf.images().keySet()));
        assertEquals(List.of(new ImportWarning("sopManager.import.warning.missingFigures", 1)), pdf.warnings());
        assertEquals("= Einleitung =\n\n"
            + "Ein Absatz mit //kursivem// Text.\n\n"
            + "Die Hände werden geschaffen, bei OP-Beginn.\n\n"
            + "(% style=\"list-style-type: gkh-decimal-parenthesis\" class=\"sop-list\" %)\n"
            + "1. Erster Schritt\n"
            + "1. Zweiter Schritt\n"
            + "(% style=\"list-style-type: gkh-lower-alpha-parenthesis\" class=\"sop-list\" %)\n"
            + "11. Unterpunkt\n\n"
            + "* Ein Punkt\n\n"
            + "Nach der Liste.\n\n"
            + "(% start=\"3\" class=\"sop-list\" %)\n"
            + "1. Dritter Schritt\n\n"
            + "* Strich\n\n"
            + "|=Material|=Menge\n"
            + "|Seife|1 Flasche\n"
            + "|(% colspan=\"2\" %)Summe\n\n"
            + "[[image:figure-1.png||width=\"53\"]]\n\n"
            + "Hinweis\n\n"
            + "Im Container.", render(pdf.content()));
    }

    private static void writeHeaderFooter(TaggedPdf pdf) throws Exception
    {
        // The logo on the left, the code and the title aligned on the right.
        pdf.artifact("GKH", 72, 800);
        pdf.artifact("ANA_AA_9.201", 440, 800);
        pdf.artifact("Synthetische Anweisung", 400, 788);
        // The release details: two labels in narrow cells close to each other, and the original document.
        pdf.artifact("Freigabe am:", 72, 70);
        pdf.artifact("Freigabe durch:", 170, 70);
        pdf.artifact("Revision: Revision geplant:", 300, 70);
        pdf.artifact("Seite", 480, 70);
        pdf.artifact("01.02.2026", 72, 58);
        pdf.artifact("Dr. Test", 170, 58);
        pdf.artifact("3", 305, 58);
        pdf.artifact("01.02.2029", 370, 58);
        pdf.artifact("Seite 1 / 1", 480, 58);
        pdf.artifact("W:\\QM\\ANA_AA_9.201_Synthetisch.doc", 72, 40);
    }

    private static void writeLists(TaggedPdf pdf, PDStructureElement document) throws Exception
    {
        // Word: the items wrapped in empty lists, their label at the start of their text, a list following an item
        // being its sub-list, a bullet after numbered items.
        PDStructureElement list = pdf.element("L", document);
        PDStructureElement wrapper = pdf.element("L", pdf.element("L", list));
        writeItem(pdf, wrapper, "1)", "Erster Schritt", 640);
        writeItem(pdf, list, "2)", "Zweiter Schritt", 628);
        writeItem(pdf, pdf.element("L", list), "a)", "Unterpunkt", 616);
        writeItem(pdf, list, "•", "Ein Punkt", 604);
        pdf.line(pdf.element("P", document), 72, 590, "Nach der Liste.");
        writeItem(pdf, pdf.element("L", document), "3.", "Dritter Schritt", 576);
        // LibreOffice: the label in its own element.
        PDStructureElement item = pdf.element("LI", pdf.element("L", document));
        pdf.line(pdf.element("Lbl", item), 72, 562, "–");
        pdf.line(pdf.element("P", pdf.element("LBody", item)), 90, 562, "Strich");
    }

    private static void writeItem(TaggedPdf pdf, PDStructureElement list, String label, String text, float y)
        throws Exception
    {
        PDStructureElement body = pdf.element("LBody", pdf.element("LI", list));
        // The label and the text separated by a tab: a gap, not a space.
        pdf.line(body, 72, y, label);
        pdf.line(body, 90, y, text);
    }

    private static void writeTable(TaggedPdf pdf, PDStructureElement document) throws Exception
    {
        PDStructureElement table = pdf.element("Table", document);
        PDStructureElement head = pdf.element("TR", pdf.element("THead", table));
        pdf.line(pdf.element("P", pdf.element("TH", head)), 72, 520, "Material");
        pdf.line(pdf.element("P", pdf.element("TH", head)), 200, 520, "Menge");
        PDStructureElement body = pdf.element("TBody", table);
        PDStructureElement row = pdf.element("TR", body);
        // The text directly in the cell, and an element of Word between the cells.
        pdf.line(pdf.element("TD", row), 72, 506, "Seife");
        pdf.element("Span", row);
        pdf.line(pdf.element("P", pdf.element("TD", row)), 200, 506, "1 Flasche");
        PDStructureElement total = pdf.element("TD", pdf.element("TR", body));
        TaggedPdf.span(total, 2);
        pdf.line(pdf.element("P", total), 72, 492, "Summe");
        // A row without cells.
        pdf.element("TR", body);
    }
}
